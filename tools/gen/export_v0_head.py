#!/usr/bin/env python3
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import joblib


def _format_array(name: str, values) -> str:
    rows = []
    for start in range(0, len(values), 4):
        chunk = ", ".join(f"{float(value):.17g}" for value in values[start : start + 4])
        rows.append(f"    {chunk},")
    return (
        f"inline constexpr double {name}[{len(values)}] = {{\n"
        + "\n".join(rows)
        + "\n};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "bundle",
        type=Path,
        nargs="?",
        default=Path("artifacts/model/model.joblib"),
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--model-version", default="v0-wavlm-large-l12-hqq4-b128")
    args = parser.parse_args()

    bundle = joblib.load(args.bundle)
    pipeline = bundle["model"]
    imputer = pipeline.named_steps["imputer"]
    scaler = pipeline.named_steps["scaler"]
    classifier = pipeline.named_steps["model"]
    if list(bundle["class_names"]) != [
        "male_natural",
        "male_unnatural",
        "female_natural",
    ]:
        raise SystemExit("unsupported class order")
    if classifier.coef_.shape != (3, 1024):
        raise SystemExit("unsupported classifier dimensions")

    coefficient_rows = [list(row) for row in classifier.coef_]
    coefficient_flat = [value for row in coefficient_rows for value in row]
    digest = hashlib.sha256(args.bundle.read_bytes()).hexdigest()
    text = """// Generated by tools/gen/export_v0_head.py. Do not edit by hand.
#ifndef PITCHEE_V0_HEAD_DATA_HPP
#define PITCHEE_V0_HEAD_DATA_HPP

#include <cstddef>

namespace pitchee::v0 {

inline constexpr int kFeatureCount = 1024;
inline constexpr double kTemperature = %.17g;
inline constexpr char kModelVersion[] = "%s";
inline constexpr char kHeadSha256[] = "%s";

%s
%s
%s
%s

}  // namespace pitchee::v0

#endif
""" % (
        float(bundle["temperature"]),
        args.model_version,
        digest,
        _format_array("kImputerStatistics", imputer.statistics_),
        _format_array("kScalerMean", scaler.mean_),
        _format_array("kScalerScale", scaler.scale_),
        _format_array("kCoefficients", coefficient_flat),
    )
    intercept = ", ".join(f"{float(value):.17g}" for value in classifier.intercept_)
    text = text.replace(
        "inline constexpr char kHeadSha256[]",
        "inline constexpr double kIntercept[3] = {%s};\ninline constexpr char kHeadSha256[]"
        % intercept,
        1,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"wrote {args.output} ({args.output.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
